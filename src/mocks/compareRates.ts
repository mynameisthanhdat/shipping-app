export const DEFAULT_SHIPPING_TYPE: ShippingTypeId = 'parcels-satchels';
export const DEFAULT_ORIGIN: CityId = 'sydney';

export const getShippingType = (id: ShippingTypeId): ShippingType =>
  SHIPPING_TYPES.find((type) => type.id === id) ?? SHIPPING_TYPES[0];

/**
 * Builds the destination cards for one origin. The origin's own city comes
 * first, labelled "<City> Local", followed by the remaining cities in order.
 */
export const getRateCards = (
  shippingTypeId: ShippingTypeId,
  originId: CityId
): RateCard[] => {
  const type = getShippingType(shippingTypeId);
  const lanes = RATES[shippingTypeId][originId];
  const destinations = [
    ...CITIES.filter((city) => city.id === originId),
    ...CITIES.filter((city) => city.id !== originId),
  ];

  return destinations.map((city) => ({
    destinationId: city.id,
    title: city.id === originId ? `${city.label} Local` : city.label,
    rows: lanes[city.id].map(([member, frequentUser], index) => ({
      weight: type.weights[index],
      itemType: type.itemType,
      member,
      frequentUser,
    })),
  }));
};
